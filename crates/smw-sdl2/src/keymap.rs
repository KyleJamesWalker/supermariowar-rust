//! SDL2's scancode names and default keymap: the table smw-headless reads (crates/smw-headless/src/sdl2_keys.txt).

use sdl2::sys::{SDL_InitSubSystem, SDL_QuitSubSystem, SDL_Scancode, SDL_INIT_VIDEO};
use std::ffi::CStr;
use std::fmt::Write;

// sdl2-sys takes `SDL_Scancode`, an enum without the unnamed values.
extern "C" {
    fn SDL_GetScancodeName(scancode: i32) -> *const std::ffi::c_char;
    fn SDL_GetKeyFromScancode(scancode: i32) -> i32;
}

/// Opens SDL's video on the dummy driver, which keeps the default keymap, and lists every named scancode with a
/// key as `<scancode> <keycode> <name>`. SDL versions differ in which keyless scancodes have names. Returns the
/// table's text.
pub fn measure() -> String {
    let mut out = String::from(
        "# Generated by `cargo run -p smw-sdl2 --example sdl2_keys`: SDL2 on the dummy video driver.\n\
         # <scancode> <SDL_GetKeyFromScancode> <SDL_GetScancodeName>\n",
    );
    // SAFETY: single-threaded tool; SDL returns a static name, empty when unnamed, for every scancode below the count.
    unsafe {
        sdl2::sys::SDL_SetHintWithPriority(sdl2::sys::SDL_HINT_VIDEODRIVER.as_ptr().cast(), c"dummy".as_ptr(), sdl2::sys::SDL_HintPriority::SDL_HINT_OVERRIDE);
        assert_eq!(SDL_InitSubSystem(SDL_INIT_VIDEO), 0, "SDL_InitSubSystem failed");
        for s in 0..SDL_Scancode::SDL_NUM_SCANCODES as i32 {
            let name = CStr::from_ptr(SDL_GetScancodeName(s)).to_string_lossy();
            let key = SDL_GetKeyFromScancode(s);
            if !name.is_empty() && key != 0 {
                let _ = writeln!(out, "{} {} {}", s, key, name);
            }
        }
        SDL_QuitSubSystem(SDL_INIT_VIDEO);
    }
    out
}
